/**
 * The map of a person: what Tacit is curious about, and why.
 *
 * Every thread names what reads its answer (`uses`). A thread nothing uses
 * does not belong here: curiosity is in service of being useful, and the
 * person can ask "why do you want to know?" of any question and get the
 * answer from this file.
 *
 * Depth is how far a thread has gone:
 *   1  the fact        "I wake up around six"
 *   2  the reason      "because the market opens and I like a head start"
 *   3  a story         "the one morning I slept in was the day…"
 * Knowing a person is mostly depth 2 and 3. A form only ever reaches 1.
 *
 * Private areas — health, faith, politics, intimate life — are never opened
 * by Tacit until the person has said yes to the area itself, once.
 */

export type Use =
  | 'briefing' | 'desk' | 'calendar' | 'gifts' | 'tone' | 'planning'
  | 'reasoning' | 'settings' | 'suggestions' | 'reminders';

export type Domain = {
  id: string;
  name: string;
  /** Why Tacit wants this area, said to the person if they ask. */
  why: string;
  /** Opened only after the person says yes to the area. */
  private?: boolean;
  /** How Tacit asks to enter a private area. */
  ask?: string;
};

export type Thread = {
  id: string;
  domain: string;
  topic: string;
  /** Ways to open it, so the same question never sounds the same twice. */
  open: string[];
  /** Depth 2: the reason behind it. */
  deeper: string;
  /** Depth 3: a story or an example. */
  story: string;
  /** Words that, said in passing, make this thread the natural next one. */
  cues: string[];
  uses: Use[];
};

